const round2 = (n) => Math.round(n * 100) / 100

function variants(price) {
  return [
    { id: "small", label: "100 seedlings", count: 100, price: round2(price), unitLabel: "per 100 seedlings" },
    { id: "medium", label: "500 seedlings", count: 500, price: round2(price * 4.6), unitLabel: "per 500 seedlings" },
    { id: "large", label: "1,000 seedlings", count: 1000, price: round2(price * 8.8), unitLabel: "per 1,000 seedlings" },
  ]
}

function product({
  id,
  slug,
  name,
  species,
  materialType,
  aliases,
  supplierCount,
  price,
  description,
  image,
  tags,
  stockStatus,
  domain,
  featured,
  productVariants,
}) {
  const evidenceNote =
    supplierCount > 0
      ? "Nursery supply is matched from the East Africa nursery database."
      : "Genetic material drawn from Information Pack - Large processors_v2.pptx; nursery supply is matched independently."

  return {
    id,
    slug,
    shop: "seedlings",
    name,
    species,
    materialType,
    nurseryVarietyAliases: aliases,
    supplierCount,
    evidenceNote,
    kind: "product",
    unitLabel: "per package",
    price: round2(price),
    currency: "USD",
    description,
    image,
    tags,
    stockStatus,
    domain,
    featured,
    variants: productVariants ?? variants(price),
  }
}

function hybridProduct({ codePrefix, parentName, codes, price, image, featured = false, supplierByCode = {} }) {
  const supplierCount = Object.values(supplierByCode).reduce((total, count) => total + count, 0)
  const productVariants = codes.map((code) => ({
    id: `${codePrefix.toLowerCase()}-${code}`,
    label: `Variety ${code}`,
    count: 100,
    price: round2(price),
    unitLabel: "per 100 seedlings",
    description: `Clone ${code} of ${parentName}`,
  }))

  return product({
    id: `seedlings-${codePrefix.toLowerCase()}-hybrid`,
    slug: `${codePrefix.toLowerCase()}-hybrid-seedlings`,
    name: parentName,
    species: "Eucalyptus",
    materialType: "Hybrid / clonal material",
    aliases: [parentName, ...codes.map((code) => `${codePrefix} ${code}`)],
    supplierCount,
    price,
    description: `Choose from ${codes.map((code) => `${codePrefix} ${code}`).join(", ")}. Nursery matches remain tied to records that explicitly name the clone code.`,
    image,
    tags: [featured ? "featured" : "new", "hybrid", "clonal", "timber"],
    stockStatus: supplierCount > 0 ? "limited" : "quote",
    domain: "timber",
    featured,
    productVariants,
  })
}

